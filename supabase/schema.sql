drop policy if exists "admin upload catalog images" on storage.objects;
create policy "admin upload catalog images" on storage.objects for insert with check (bucket_id = 'catalog-media' and public.is_catalog_admin());
drop policy if exists "admin update catalog images" on storage.objects;
create policy "admin update catalog images" on storage.objects for update using (bucket_id = 'catalog-media' and public.is_catalog_admin());
